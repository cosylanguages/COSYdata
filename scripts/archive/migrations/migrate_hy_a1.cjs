function getAllExistingHyWordsAndIds() {
  const existingWords = new Set();
  const existingIds = new Set();
  function scan(dir) {
    if (!fs.existsSync(dir)) return;
    fs.readdirSync(dir, { withFileTypes: true }).forEach(ent => {
      const full = path.join(dir, ent.name);
      if (ent.isDirectory()) scan(full);
      else if (ent.isFile() && ent.name.endsWith('.json') && ent.name !== 'index.json' && ent.name !== 'flat-index.json') {
        const content = JSON.parse(fs.readFileSync(full, 'utf8'));
        if (Array.isArray(content)) {
          content.forEach(e => {
            if (e.word) existingWords.add(e.word.trim());
            if (e.id) existingIds.add(e.id);
          });
        }
      }
    });
  }
  scan(cosyDataHyDir);
  return { existingWords, existingIds };
}

function mapToThemeFile(item, form, word) {
  const fileKey = (item._file || '').toLowerCase();
  const theme = (item.theme || '').toLowerCase();

  if (fileKey === 'greetings.js' || fileKey === 'social.js' || form === 'phrase') return 'expressions.json';
  if (fileKey === 'numbers.js' || theme.includes('number')) return 'numbers.json';
  if (fileKey === 'grammar_elements.js') {
    if (form === 'preposition' || form === 'postposition') return 'prepositions.json';
    if (form === 'pronoun' || form === 'determiner') return 'pronouns.json';
    if (form === 'conjunction' || form === 'adverb') return 'adverbs_connectors.json';
    return 'adverbs_connectors.json';
  }

  if (form === 'verb' || fileKey === 'verbs.js') {
    if (['լինել', 'ունենալ', 'կարողանալ', 'ուզել'].includes(word)) return 'auxiliary_verbs.json';
    return 'daily_verbs.json';
  }

  if (form === 'adjective' || fileKey === 'adjectives.js' || fileKey === 'colours.js') {
    if (['արևոտ', 'անձրևոտ', 'սառը', 'տաք', 'զով'].includes(word)) return 'weather.json';
    if (['զբաղված', 'հոգնած', 'տխուր', 'ուրախ', 'երջանիկ', 'բարկացած', 'զարմացած', 'վախեցած'].includes(word)) return 'feelings.json';
    return 'general_adjectives.json';
  }

  if (fileKey === 'locations.js' || fileKey === 'places.js' || fileKey === 'travel.js') return 'places_transport.json';
  if (fileKey === 'nationalities.js' || fileKey === 'people.js') return 'nationalities.json';
  if (fileKey === 'food_drink.js' || fileKey === 'dishes.js') return 'food_drink.json';
  if (fileKey === 'animals.js' || fileKey === 'nature.js') return 'animals.json';
  if (fileKey === 'body.js') return 'body_health.json';
  if (fileKey === 'clothes.js' || fileKey === 'shopping.js') return 'clothes.json';
  if (fileKey === 'family.js') return 'family.json';
  if (fileKey === 'furniture.js') return 'house_furniture.json';
  if (fileKey === 'jobs.js') return 'jobs.json';
  if (fileKey === 'school.js' || fileKey === 'technology.js') return 'school.json';

  return 'common_nouns.json';
}

function normalizeTranscription(word, tr) {
  if (tr && typeof tr === 'string' && tr.trim() && tr.trim() !== '/') {
    let t = tr.trim();
    if (!t.startsWith('/')) t = '/' + t;
    if (!t.endsWith('/')) t = t + '/';
    return t;
  }
  if (hyIPA[word]) return hyIPA[word];
  const slug = transliterate(word);
  return `/${slug}/`;
}

