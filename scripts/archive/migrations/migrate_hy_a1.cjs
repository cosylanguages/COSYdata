function sanitizeAntonyms(ants) {
  if (!Array.isArray(ants) || ants.length === 0) return null;
  const clean = ants
    .filter(a => typeof a === 'string' && a.trim() && /[\u0530-\u058F]/.test(a))
    .map(a => a.trim());
  return clean.length > 0 ? clean : null;
}

function processHyMigration() {
  console.log('Starting Armenian (hy) A1 gap migration...');

  const { existingWords, existingIds } = getAllExistingHyWordsAndIds();
  console.log(`Existing Armenian words in repo: ${existingWords.size}`);
  console.log(`Existing Armenian IDs in repo: ${existingIds.size}`);

  function walk(dir) {
    let results = [];
    if (!fs.existsSync(dir)) return results;
    fs.readdirSync(dir).forEach(file => {
      const full = path.join(dir, file);
      if (fs.statSync(full).isDirectory()) results = results.concat(walk(full));
      else if (file.endsWith('.js')) results.push(full);
    });
    return results;
  }

  const jsFiles = walk(cosyLangDir);
  const rawJsItems = [];

  jsFiles.forEach(fullPath => {
    const code = fs.readFileSync(fullPath, 'utf8');
    const sandbox = { window: {}, module: { exports: {} }, exports: {} };
    try {
      vm.runInNewContext(code, sandbox);
      let list = sandbox.window.vocabularyData?.hy || [];
      if (!list.length && Array.isArray(sandbox.module.exports)) list = sandbox.module.exports;
      list.forEach(item => rawJsItems.push({ ...item, _file: path.basename(fullPath) }));
    } catch (e) {
      console.error(`Error loading ${fullPath}:`, e.message);
    }
  });

  const candidateItems = [];
  const candidateSet = new Set();

  rawJsItems.forEach(item => {
    if (!item.word || typeof item.word !== 'string') return;
    const rawWord = item.word.trim();
    const slug = transliterate(rawWord);
    const fileKey = item._file || '';

    let form = (item.form || '').toLowerCase();
    if (fileKey === 'greetings.js' || fileKey === 'social.js' || rawWord.includes('?') || rawWord === 'բարի լույս' || rawWord === 'անկողին գնալ' || rawWord === 'լրիվ դրույք' || rawWord === 'կես դրույք' || rawWord === 'բաց թողնել' || rawWord === 'թույլ տալ' || rawWord === 'կարիք ունենալ' || rawWord === 'շնորհակալություն հայտնել' || rawWord === 'սթրեսի մեջ' || rawWord === 'պարտք լինել' || rawWord === 'վեր կենալ') {
      form = 'phrase';
    }
    if (fileKey === 'locations.js' || fileKey === 'nationalities.js' || fileKey === 'people.js' || fileKey === 'dishes.js') {
      if (form !== 'phrase') form = 'noun';
    }
    if (fileKey === 'grammar_elements.js') {
      if (form === 'postposition') form = 'preposition';
      if (form === 'determiner' || form === 'particle') form = 'pronoun';
    }
    if (!form) {
      form = 'noun';
    }

    const potentialId = `hy:${slug}:${form}`;

    if (existingWords.has(rawWord) || existingIds.has(potentialId) || candidateSet.has(rawWord)) {
      return;
    }

    candidateSet.add(rawWord);
    existingIds.add(potentialId);
    candidateItems.push({ ...item, _computedForm: form });
  });

  console.log(`Strict non-duplicate candidates to convert: ${candidateItems.length}`);

  if (!fs.existsSync(cosyDataA0A1Dir)) {
    fs.mkdirSync(cosyDataA0A1Dir, { recursive: true });
  }

  const convertedByFile = {};

  let addedCount = 0;

  candidateItems.forEach(item => {
    const rawWord = item.word.trim();
    const slug = transliterate(rawWord);
    const form = item._computedForm;
    const entryId = `hy:${slug}:${form}`;

    // Definitions
    let defs = [];
    if (Array.isArray(item.definitions)) {
      item.definitions.forEach(d => {
        if (typeof d === 'string' && d.trim()) defs.push(d.trim());
        else if (d && typeof d.text === 'string' && d.text.trim()) defs.push(d.text.trim());
      });
    } else if (typeof item.definition === 'string' && item.definition.trim()) {
      defs.push(item.definition.trim());
    }

    if (defs.length === 0) {
      if (form === 'verb') defs = [`Կատարել ${rawWord} գործողությունը։`];
      else if (form === 'adjective') defs = [`Հատկանիշ կամ որակ՝ ${rawWord}։`];
      else if (form === 'phrase') defs = [`Արտահայտություն հայերենում՝ ${rawWord}։`];
      else defs = [`Հասկացություն կամ առարկա՝ ${rawWord}։`];
    }

    const exSentence = generateExampleSentence(rawWord, form);
    const targetFile = mapToThemeFile(item, form, rawWord);
    const themeName = targetFile.replace('.json', '');

    const newEntry = {
      id: entryId,
      word: rawWord,
      language: 'hy',
      form: form,
      level: 'A1',
      transcription: normalizeTranscription(rawWord, item.transcription),
      definitions: defs,
      examples: [exSentence],
      domain: 'general',
      theme: themeName,
      updated: '2025-01-15'
    };

    if (item.emoji && typeof item.emoji === 'string' && item.emoji.trim()) {
      newEntry.emoji = item.emoji.trim();
    } else {
      newEntry.no_emoji = true;
    }

    const cleanAnts = sanitizeAntonyms(item.antonyms);
    if (cleanAnts) {
      newEntry.antonyms = cleanAnts;
    } else {
      newEntry.no_antonym = true;
    }

    // Noun specific fields
    if (form === 'noun') {
      const properNouns = [
        'Ֆրանսիա', 'Իտալիա', 'Ռուսաստան', 'Հունաստան', 'Անգլիա', 'Իսպանիա', 'ԱՄՆ',
        'Փարիզ', 'Լոնդոն', 'Հռոմ', 'Մոսկվա', 'Աթենք', 'Նյու Յորք'
      ];
      const isProper = properNouns.includes(rawWord);

      if (isProper) {
        newEntry.countability = 'invariable';
      } else if (['լավաշ', 'գին', 'դրամ', 'կարագ', 'խորոված', 'տոլմա'].includes(rawWord)) {
        newEntry.countability = 'uncountable';
      } else {
        newEntry.countability = 'countable';
        let plural = rawWord + 'ներ';
        if (rawWord.endsWith('ա') || rawWord.endsWith('ի')) plural = rawWord + 'ներ';
        if (rawWord === 'եղբայր') plural = 'եղբայրներ';
        if (rawWord === 'մարդ') plural = 'մարդիկ';
        if (rawWord === 'կին') plural = 'կանայք';
        if (rawWord === 'երեխա') plural = 'երեխաներ';
        if (rawWord === 'ձուկ') plural = 'ձկներ';
        if (rawWord === 'ծառ') plural = 'ծառեր';
        if (rawWord === 'գետ') plural = 'գետեր';
        if (rawWord === 'ծով') plural = 'ծովեր';
        if (rawWord === 'տուն') plural = 'տներ';
        if (rawWord === 'դաս') plural = 'դասեր';
        if (rawWord === 'պապ') plural = 'պապեր';
        if (rawWord === 'տատ') plural = 'տատեր';
        if (rawWord === 'տոն') plural = 'տոներ';
        if (rawWord === 'քույր') plural = 'քույրեր';

        newEntry.plural_form = plural;
      }
    }

    if (!convertedByFile[targetFile]) convertedByFile[targetFile] = [];
    convertedByFile[targetFile].push(newEntry);
    addedCount++;
  });

  // 5. Append or write converted entries
  for (const [file, entries] of Object.entries(convertedByFile)) {
    if (entries.length === 0) continue;
    const filePath = path.join(cosyDataA0A1Dir, file);
    let existingContent = [];
    if (fs.existsSync(filePath)) {
      existingContent = JSON.parse(fs.readFileSync(filePath, 'utf8'));
    }
    const updatedContent = [...existingContent, ...entries];
    fs.writeFileSync(filePath, JSON.stringify(updatedContent, null, 2) + '\n', 'utf8');
    console.log(`Wrote/Appended ${entries.length} entries to vocabulary/hy/a0_a1/${file}`);
  }

  console.log(`Armenian migration execution complete! Total non-duplicate entries added: ${addedCount}`);
}

processHyMigration();
