const themeFiles = {};

function addToTheme(theme, entry) {
  if (existingIds.has(entry.id)) return;
  existingIds.add(entry.id);

  if (!themeFiles[theme]) themeFiles[theme] = [];
  themeFiles[theme].push(entry);
}

