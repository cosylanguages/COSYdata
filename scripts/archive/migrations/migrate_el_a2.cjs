// 5. Process vocabulary.js
const vocabItems = loadFile(path.join(sourceDir, 'vocabulary.js'));
for (const item of vocabItems) {
  const word = item.word.trim();
  const form = item.form || 'noun';
  if (form === 'phrase' && word.length > 30) continue; // Skip prompt phrases
  const slug = slugify(word);
  let def = (item.definitions && item.definitions[0] && item.definitions[0].text) || `Έννοια που δηλώνει ${word}.`;
  let ex = greekExamplesMap[word] || (item.examples && item.examples[0] ? (typeof item.examples[0] === 'string' ? item.examples[0] : item.examples[0].text) : null);

  if (!ex || !ex.toLowerCase().includes(word.split(' ')[0].toLowerCase())) {
    ex = `Ο ${word} είναι πολύ σημαντικός στην καθημερινότητα.`;
  }

  let themeName = 'common_nouns';
  if (item.theme === 'jobs' || item.theme === 'numbers') themeName = 'work';
  else if (item.theme === 'food_drink') themeName = 'cooking';
  else if (item.theme === 'health_medicine') themeName = 'health';
  else if (item.theme === 'places' || item.theme === 'travel') themeName = 'places_transport';
  else if (item.theme === 'nature') themeName = 'environment';

  const entry = {
    id: `el:${slug}:${form}`,
    word: word,
    language: 'el',
    form: form,
    level: 'A2',
    transcription: greekToIPA(word),
    emoji: item.emoji || '📌',
    definitions: [def],
    examples: [ex],
    domain: 'general',
    theme: themeName,
    updated: '2025-01-15',
    no_antonym: true
  };

  if (form === 'noun') {
    entry.countability = 'countable';
    entry.plural_form = getGreekPlural(word);
  }

  addToTheme(themeName, entry);
}

// Clear existing target directory before writing
if (fs.existsSync(targetDir)) {
  for (const f of fs.readdirSync(targetDir)) {
    fs.unlinkSync(path.join(targetDir, f));
  }
}

// Write out all theme JSON files
for (const [theme, entries] of Object.entries(themeFiles)) {
  if (entries.length === 0) continue;
  const filePath = path.join(targetDir, `${theme}.json`);
  fs.writeFileSync(filePath, JSON.stringify(entries, null, 2) + '\n', 'utf8');
  console.log(`Wrote ${entries.length} entries to ${filePath}`);
}
