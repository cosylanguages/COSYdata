function loadFile(filePath) {
  const content = fs.readFileSync(filePath, 'utf8');
  const sandbox = { window: {}, module: { exports: {} }, exports: {} };
  try {
    vm.runInNewContext(content, sandbox);
    for (const k of Object.keys(sandbox)) {
      if (Array.isArray(sandbox[k])) return sandbox[k];
    }
    for (const k of Object.keys(sandbox.window)) {
      if (Array.isArray(sandbox.window[k])) return sandbox.window[k];
    }
  } catch (e) {}
  const match = content.match(/const data = (\[[\s\S]*?\]);/);
  if (match) {
    const sb = {};
    vm.runInNewContext(`data = ${match[1]}`, sb);
    return sb.data;
  }
  return [];
}

function slugify(text) {
  const map = {
    'α': 'a', 'ά': 'a', 'β': 'v', 'γ': 'g', 'δ': 'd', 'ε': 'e', 'έ': 'e', 'ζ': 'z',
    'η': 'i', 'ή': 'i', 'θ': 'th', 'ι': 'i', 'ί': 'i', 'ϊ': 'i', 'ΐ': 'i', 'κ': 'k',
    'λ': 'l', 'μ': 'm', 'ν': 'n', 'ξ': 'x', 'ο': 'o', 'ό': 'o', 'π': 'p', 'ρ': 'r',
    'σ': 's', 'ς': 's', 'τ': 't', 'υ': 'y', 'ύ': 'y', 'ϋ': 'y', 'ΰ': 'y', 'φ': 'f',
    'χ': 'ch', 'ψ': 'ps', 'ω': 'o', 'ώ': 'o',
    'Α': 'a', 'Ά': 'a', 'Β': 'v', 'Γ': 'g', 'Δ': 'd', 'Ε': 'e', 'Έ': 'e', 'Ζ': 'z',
    'Η': 'i', 'Ή': 'i', 'Θ': 'th', 'Ι': 'i', 'Ί': 'i', 'Κ': 'k', 'Λ': 'l', 'Μ': 'm',
    'Ν': 'n', 'Ξ': 'x', 'Ο': 'o', 'Ό': 'o', 'Π': 'p', 'Ρ': 'r', 'Σ': 's', 'Τ': 't',
    'Υ': 'y', 'Ύ': 'y', 'Φ': 'f', 'Χ': 'ch', 'Ψ': 'ps', 'Ω': 'o', 'Ώ': 'o'
  };
  return text
    .split('')
    .map(ch => map[ch] !== undefined ? map[ch] : ch)
    .join('')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function greekToIPA(word) {
  let w = word.toLowerCase();
  w = w.replace(/μπ/g, 'b')
       .replace(/ντ/g, 'd')
       .replace(/γκ/g, 'g')
       .replace(/γγ/g, 'ŋg')
       .replace(/τσ/g, 'ts')
       .replace(/τζ/g, 'dz')
       .replace(/ει|οι|υι/g, 'i')
       .replace(/αι/g, 'e')
       .replace(/αυ(?=[πτεκχψσς]|$)/g, 'af')
       .replace(/αυ/g, 'av')
       .replace(/ευ(?=[πτεκχψσς]|$)/g, 'ef')
       .replace(/ευ/g, 'ev');

  const map = {
    'α': 'a', 'ά': 'a', 'β': 'v', 'γ': 'ɣ', 'δ': 'ð', 'ε': 'e', 'έ': 'e', 'ζ': 'z',
    'η': 'i', 'ή': 'i', 'θ': 'θ', 'ι': 'i', 'ί': 'i', 'ϊ': 'i', 'ΐ': 'i', 'κ': 'k',
    'λ': 'l', 'μ': 'm', 'ν': 'n', 'ξ': 'ks', 'ο': 'o', 'ό': 'o', 'π': 'p', 'ρ': 'r',
    'σ': 's', 'ς': 's', 'τ': 't', 'υ': 'i', 'ύ': 'i', 'ϋ': 'i', 'ΰ': 'i', 'φ': 'f',
    'χ': 'x', 'ψ': 'ps', 'ω': 'o', 'ώ': 'o'
  };

  let ipa = w.split('').map(ch => map[ch] !== undefined ? map[ch] : ch).join('');
  return '/' + ipa + '/';
}

function getGreekPlural(word) {
  const w = word.trim();
  if (w.endsWith('ης')) return w.slice(0, -2) + 'ες';
  if (w.endsWith('ής')) return w.slice(0, -2) + 'ές';
  if (w.endsWith('ος')) return w.slice(0, -2) + 'οι';
  if (w.endsWith('ός')) return w.slice(0, -2) + 'οί';
  if (w.endsWith('α')) return w.slice(0, -1) + 'ες';
  if (w.endsWith('ά')) return w.slice(0, -1) + 'ές';
  if (w.endsWith('ι')) return w.slice(0, -1) + 'ια';
  if (w.endsWith('ί')) return w.slice(0, -1) + 'ιά';
  if (w.endsWith('ο')) return w.slice(0, -1) + 'α';
  if (w.endsWith('ό')) return w.slice(0, -1) + 'ά';
  if (w.endsWith('μα')) return w.slice(0, -2) + 'ματα';
  if (w.endsWith('υς')) return w.slice(0, -2) + 'εις';
  return w + 'ες';
}

