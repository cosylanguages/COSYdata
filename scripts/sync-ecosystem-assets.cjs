#!/usr/bin/env node
/**
 * Vendors the ecosystem presentation assets COSYdata needs, so that no COSYdata
 * page loads CSS, JavaScript or fonts from a sibling repository at runtime.
 *
 *   node scripts/sync-ecosystem-assets.cjs --update           # download, rewrite ASSETS.json
 *   node scripts/sync-ecosystem-assets.cjs --check            # offline: files match ASSETS.json
 *   node scripts/sync-ecosystem-assets.cjs --check --remote   # also compare against upstream
 *
 * Copies are byte-identical to upstream on purpose: never edit a vendored file,
 * because --check fails on a hash mismatch. Re-run --update to pick up upstream
 * changes, and review the diff like any other dependency bump.
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const ROOT = path.resolve(__dirname, '..');
const VENDOR = path.join(ROOT, 'shared', 'vendor');
const MANIFEST = path.join(VENDOR, 'ASSETS.json');

const LANGUAGES = 'https://cosylanguages.github.io/COSYlanguages';
const TOOLS = 'https://cosylanguages.github.io/COSYtools';

const FONT_FILES = [
  'commissioner-cyrillic-ext-wght-normal.woff2',
  'commissioner-cyrillic-wght-normal.woff2',
  'commissioner-greek-wght-normal.woff2',
  'commissioner-latin-ext-wght-normal.woff2',
  'commissioner-latin-wght-normal.woff2',
  'fraunces-latin-ext-soft-normal.woff2',
  'fraunces-latin-soft-normal.woff2',
  'literata-cyrillic-wght-normal.woff2',
  'literata-greek-wght-normal.woff2',
  'literata-latin-wght-normal.woff2'
];

const ASSETS = [
  {
    dest: 'tokens.css',
    source: `${LANGUAGES}/shared/css/tokens.css`,
    note: 'Ecosystem design tokens. Authoritative copy lives in COSYlanguages; do not fork values here.'
  },
  {
    dest: 'css/fonts.css',
    source: `${LANGUAGES}/css/fonts.css`,
    note: 'Self-hosted Fraunces, Literata and Commissioner. Relative ../fonts/ paths resolve inside shared/vendor/.'
  },
  {
    dest: 'css/ecosystem-strip.css',
    source: `${LANGUAGES}/css/ecosystem-strip.css`,
    note: 'Cross-site navigation strip styling.'
  },
  {
    dest: 'js/ecosystem-strip.js',
    source: `${LANGUAGES}/js/ecosystem-strip.js`,
    note: 'Cross-site navigation strip. Reads the shared cosy-auth key; contains no asset URLs.'
  },
  {
    dest: 'css/daily-strip.css',
    source: `${LANGUAGES}/css/daily-strip.css`,
    note: 'Daily strip widget styling.'
  },
  {
    dest: 'js/daily-strip.js',
    source: `${LANGUAGES}/js/daily-strip.js`,
    note: 'Daily strip renderer. Its vocabulary calendars are COSYdata/daily/ data, so it belongs here.'
  },
  {
    dest: 'css/daily-directory.css',
    source: `${LANGUAGES}/css/daily-directory.css`,
    note: 'Daily directory card grid styling.'
  },
  {
    dest: 'js/daily-directory.js',
    source: `${LANGUAGES}/js/daily-directory.js`,
    note: 'Daily directory card grid. Contains no asset URLs.'
  },
  {
    dest: 'js/vocabulary-relations.js',
    source: `${TOOLS}/shared/js/vocabulary-relations.js`,
    note: 'Antonym/synonym lexicon reader. Passed a local lexicon URL by shared/dictionary-ui.js.'
  },
  {
    dest: 'js/vocabulary-relations.json',
    source: `${TOOLS}/shared/js/vocabulary-relations.json`,
    note: 'Compiled antonym/synonym lexicon. Follow-up: generate this from vocabulary entries instead of COSYtools.'
  }
].concat(
  FONT_FILES.map((file) => ({
    dest: `fonts/${file}`,
    source: `${LANGUAGES}/fonts/${file}`,
    note: 'SIL Open Font License; see fonts/LICENSE-*.txt.'
  })),
  ['fraunces', 'literata', 'commissioner'].map((family) => ({
    dest: `fonts/LICENSE-${family}.txt`,
    source: `${LANGUAGES}/fonts/LICENSE-${family}.txt`,
    note: 'Font licence, vendored with the font files as the OFL requires.'
  }))
);

function sha256(buffer) {
  return crypto.createHash('sha256').update(buffer).digest('hex');
}

function readManifest() {
  if (!fs.existsSync(MANIFEST)) return { assets: [] };
  return JSON.parse(fs.readFileSync(MANIFEST, 'utf8'));
}

function writeManifest(assets) {
  const body = {
    note: 'Pinned copies of sibling-repository assets. Generated by scripts/sync-ecosystem-assets.cjs; never edit by hand.',
    generator: 'scripts/sync-ecosystem-assets.cjs',
    assets: assets
      .slice()
      .sort((a, b) => a.dest.localeCompare(b.dest))
      .map(({ dest, source, sha256: hash, bytes, note }) => ({ dest, source, sha256: hash, bytes, note }))
  };
  fs.writeFileSync(MANIFEST, JSON.stringify(body, null, 2) + '\n');
}

async function download(url) {
  const response = await fetch(url, { redirect: 'follow' });
  if (!response.ok) throw new Error(`HTTP ${response.status} for ${url}`);
  return Buffer.from(await response.arrayBuffer());
}

async function update() {
  const recorded = [];
  for (const asset of ASSETS) {
    const buffer = await download(asset.source);
    const target = path.join(VENDOR, asset.dest);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    const previous = fs.existsSync(target) ? fs.readFileSync(target) : null;
    if (!previous || !previous.equals(buffer)) {
      fs.writeFileSync(target, buffer);
      console.log(`updated  ${asset.dest}`);
    } else {
      console.log(`unchanged ${asset.dest}`);
    }
    recorded.push({ ...asset, sha256: sha256(buffer), bytes: buffer.length });
  }
  writeManifest(recorded);
  console.log(`\nWrote ${path.relative(ROOT, MANIFEST)} with ${recorded.length} assets.`);
}

async function check({ remote }) {
  const manifest = readManifest();
  if (!manifest.assets.length) {
    console.error('shared/vendor/ASSETS.json is missing or empty. Run --update.');
    return 1;
  }
  let failures = 0;
  for (const asset of manifest.assets) {
    const target = path.join(VENDOR, asset.dest);
    if (!fs.existsSync(target)) {
      console.error(`MISSING  ${asset.dest}`);
      failures += 1;
      continue;
    }
    const local = fs.readFileSync(target);
    if (sha256(local) !== asset.sha256) {
      console.error(`MODIFIED ${asset.dest} (local copy no longer matches upstream)`);
      failures += 1;
      continue;
    }
    if (remote) {
      const upstream = await download(asset.source);
      if (sha256(upstream) !== asset.sha256) {
        console.error(`DRIFT    ${asset.dest} (upstream changed; run --update)`);
        failures += 1;
      }
    }
  }
  const expected = new Set(manifest.assets.map((asset) => asset.dest));
  const walk = (dir) =>
    fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) return walk(full);
      const rel = path.relative(VENDOR, full).split(path.sep).join('/');
      return rel === 'ASSETS.json' ? [] : [rel];
    });
  if (fs.existsSync(VENDOR)) {
    for (const rel of walk(VENDOR)) {
      if (!expected.has(rel)) {
        console.error(`UNTRACKED ${rel} (not in ASSETS.json)`);
        failures += 1;
      }
    }
  }
  if (failures) {
    console.error(`\n${failures} vendored asset problem(s).`);
    return 1;
  }
  console.log(`All ${manifest.assets.length} vendored assets verified.`);
  return 0;
}

async function main() {
  const args = process.argv.slice(2);
  if (args.includes('--update')) return update().then(() => 0);
  if (args.includes('--check')) return check({ remote: args.includes('--remote') });
  console.error('Usage: sync-ecosystem-assets.cjs --update | --check [--remote]');
  return 2;
}

main().then((code) => process.exit(code), (error) => {
  console.error(error.message);
  process.exit(1);
});
